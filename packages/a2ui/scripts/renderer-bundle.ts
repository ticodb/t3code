// @effect-diagnostics nodeBuiltinImport:off
import * as NodePath from "node:path";
import { build } from "rolldown";

export const RENDERER_MODULE_PATH = NodePath.join(import.meta.dirname, "../vendor/renderer.js");

/** The text of vendor/renderer.js for the current source and @a2ui versions. */
export async function rendererModuleSource(): Promise<string> {
  const result = await build({
    input: NodePath.join(import.meta.dirname, "../src/renderer.browser.ts"),
    platform: "browser",
    write: false,
    transform: { define: { "process.env.NODE_ENV": JSON.stringify("production") } },
    output: { format: "iife", minify: true, codeSplitting: false },
  });
  const chunk = result.output.find((output) => output.type === "chunk");
  if (chunk === undefined) throw new Error("rolldown produced no chunk");
  // Inline script text must never close its own <script> element.
  const script = chunk.code.replaceAll("</script", "<\\/script");
  return `// Generated by scripts/build-renderer.ts from @a2ui/lit and @a2ui/web_core (Apache-2.0). Do not edit.\nexport const A2UI_RENDERER_SCRIPT = ${JSON.stringify(script)};\n`;
}
